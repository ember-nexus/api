// Command mphf-builder builds, verifies and queries `.mphf` files.
//
//	mphf-builder build --input <csv|-> --output <path> --watermark-ms <n> [--generator <text>] [--gamma 2.0] [--max-levels 32]
//	mphf-builder verify <path>
//	mphf-builder lookup <path> <id>
//
// build prints a JSON summary on stdout; errors go to stderr with exit code 1.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"runtime/debug"
	"strconv"
	"strings"

	"github.com/ember-nexus/api/lib/UuidToTypeMphfLookup/mphf"
)

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "build":
		err = runBuild(os.Args[2:])
	case "verify":
		err = runVerify(os.Args[2:])
	case "lookup":
		err = runLookup(os.Args[2:])
	case "-h", "--help", "help":
		usage()
		return
	default:
		usage()
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, `usage:
  mphf-builder build --input <csv|-> --output <path> [--watermark-ms <n>] [--generator <text>] [--gamma 2.0] [--max-levels 32]
  mphf-builder verify <path>
  mphf-builder lookup <path> <id>`)
}

func runBuild(args []string) error {
	fs := flag.NewFlagSet("build", flag.ContinueOnError)
	input := fs.String("input", "", "CSV file (`<id>;<type>` per line) or - for stdin")
	output := fs.String("output", "", "output .mphf path")
	watermark := fs.Uint64("watermark-ms", 0, "watermark (UTC ms) stored in the header")
	generator := fs.String("generator", mphf.DefaultGenerator, "text for the `generated by` line of the file preface")
	gamma := fs.Float64("gamma", mphf.DefaultGamma, "BBHash gamma")
	maxLevels := fs.Int("max-levels", mphf.DefaultMaxLevels, "maximum number of BBHash levels")
	expected := fs.Int("expected-keys", 0, "pre-size the key storage (default: derived from the input file size)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *input == "" || *output == "" {
		return errors.New("--input and --output are required")
	}
	size := int64(0)
	open := func() (io.ReadCloser, error) { return os.Stdin, nil }
	attempts := 1 // stdin can only be read once
	if *input != "-" {
		open = func() (io.ReadCloser, error) { return os.Open(*input) }
		attempts = mphf.DefaultBuildAttempts
		if st, err := os.Stat(*input); err == nil && st.Mode().IsRegular() {
			size = st.Size()
		}
	}
	if *expected == 0 && size > 0 {
		// every line has at least 40 bytes, so this is an upper bound; untouched capacity is never resident
		*expected = int(size/(mphf.IDLength+3)) + 1
	}
	// the key storage is one big long-lived allocation; the GC has nothing to gain from scanning it
	debug.SetGCPercent(50)

	stats, lines, err := mphf.BuildFileResolvingConflicts(
		mphf.BuildOptions{Gamma: *gamma, MaxLevels: *maxLevels, WatermarkMs: *watermark, Generator: *generator, ExpectedKeys: *expected},
		open, *output, attempts,
		func(attempt int) {
			fmt.Fprintf(os.Stderr, "warning: build %d found two different ids with the same hash, building again with a new hash key\n", attempt)
		},
	)
	if err != nil {
		var dce *mphf.DataConflictError
		if errors.As(err, &dce) {
			for _, l := range dce.Lines {
				fmt.Fprintln(os.Stderr, "conflict:", l)
			}
		}
		return err
	}
	out := struct {
		*mphf.Stats
		Lines      int64 `json:"lines"`
		PeakRSSMiB int64 `json:"peakRssMiB"`
	}{stats, lines, peakRSSMiB()}
	return json.NewEncoder(os.Stdout).Encode(out)
}

func runVerify(args []string) error {
	if len(args) != 1 {
		return errors.New("usage: mphf-builder verify <path>")
	}
	info, err := mphf.VerifyFile(args[0])
	if err != nil {
		return err
	}
	return json.NewEncoder(os.Stdout).Encode(info)
}

func runLookup(args []string) error {
	if len(args) != 2 {
		return errors.New("usage: mphf-builder lookup <path> <id>")
	}
	t, err := mphf.Open(args[0], mphf.OpenOptions{})
	if err != nil {
		return err
	}
	defer t.Close()
	if typ, ok := t.Lookup(args[1]); ok {
		fmt.Println(typ)
	} else {
		fmt.Println("unknown")
	}
	return nil
}

// peakRSSMiB reads VmHWM from /proc/self/status (Linux only, -1 elsewhere).
func peakRSSMiB() int64 {
	b, err := os.ReadFile("/proc/self/status")
	if err != nil {
		return -1
	}
	for _, l := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(l, "VmHWM:") {
			f := strings.Fields(l)
			if len(f) >= 2 {
				if kb, err := strconv.ParseInt(f[1], 10, 64); err == nil {
					return kb / 1024
				}
			}
		}
	}
	return -1
}
