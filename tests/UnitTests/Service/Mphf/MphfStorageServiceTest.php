<?php

declare(strict_types=1);

namespace App\Tests\UnitTests\Service\Mphf;

use App\Service\Mphf\MphfStorageService;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Small;
use PHPUnit\Framework\TestCase;

#[Small]
#[CoversClass(MphfStorageService::class)]
class MphfStorageServiceTest extends TestCase
{
    private string $directory;

    protected function setUp(): void
    {
        $this->directory = sys_get_temp_dir().'/mphf-storage-test-'.bin2hex(random_bytes(6));
    }

    protected function tearDown(): void
    {
        foreach (glob($this->directory.'/{,.}*', GLOB_BRACE) ?: [] as $file) {
            if (is_file($file)) {
                unlink($file);
            }
        }
        if (is_dir($this->directory)) {
            rmdir($this->directory);
        }
    }

    private function validFile(string $path, string $content = 'payload'): void
    {
        file_put_contents($path, MphfFixture::file($content));
    }

    public function testDirectoryDefaults(): void
    {
        $this->assertSame('/dev/shm/ember-nexus-mphf', (new MphfStorageService('memory', ''))->getDirectory());
        $this->assertSame(sys_get_temp_dir().'/ember-nexus-mphf', (new MphfStorageService('disk', ''))->getDirectory());
        $this->assertSame('/custom/dir', (new MphfStorageService('memory', '/custom/dir/'))->getDirectory());
    }

    public function testVersionValidation(): void
    {
        $service = new MphfStorageService('memory', $this->directory);

        $this->assertTrue($service->isValidVersion('20260101-0317.mphf'));
        $this->assertFalse($service->isValidVersion('../20260101-0317.mphf'));
        $this->assertFalse($service->isValidVersion('20260101-0317.mphf.tmp'));
        $this->assertFalse($service->isValidVersion(''));
    }

    public function testPaths(): void
    {
        $service = new MphfStorageService('memory', $this->directory);

        $this->assertSame($this->directory.'/v.mphf', $service->getFilePath('v.mphf'));
        $this->assertSame($this->directory.'/.lock', $service->getLockFilePath());
        $this->assertSame('mphf/v.mphf', $service->getBucketKey('v.mphf'));
    }

    public function testEnsureDirectoryAndHasFile(): void
    {
        $service = new MphfStorageService('memory', $this->directory);
        $service->ensureDirectory();
        $service->ensureDirectory();

        $this->assertDirectoryExists($this->directory);
        $this->assertFalse($service->hasFile('20260101-0317.mphf'));
        $this->assertFalse($service->hasFile('invalid'));
        touch($this->directory.'/20260101-0317.mphf');
        $this->assertTrue($service->hasFile('20260101-0317.mphf'));
    }

    public function testChecksum(): void
    {
        $service = new MphfStorageService('memory', $this->directory);
        $service->ensureDirectory();
        $good = $this->directory.'/good';
        $this->validFile($good);
        $content = 'payload';
        $hash = hash('sha256', $content);
        $variants = [
            'wrong hash' => MphfFixture::preface(7, hash('sha256', 'other')).$content,
            'truncated' => MphfFixture::preface(7, $hash).'payloa',
            'extended' => MphfFixture::preface(7, $hash).$content.'x',
            'no blank line' => "MPHF\ncontent length: 7\nsha256: ".$hash."\n".$content,
            'bad magic' => 'XPHF'.substr(MphfFixture::preface(7, $hash), 4).$content,
            'no hash' => "MPHF\ncontent length: 7\n\n".$content,
            'uppercase hash' => MphfFixture::preface(7, strtoupper($hash)).$content,
            'short' => 'abc',
            'content not aligned' => "MPHF\ncontent length: 7\nsha256: ".$hash."\n\n".$content,
            '64 spaces of padding' => str_replace("\n\n", str_repeat(' ', 64)."\n\n", MphfFixture::preface(7, $hash)).$content,
            'padding on another line' => str_replace('generated by: test', 'generated by: test ', MphfFixture::preface(7, $hash)).$content,
            'padding in front of the hash' => str_replace('sha256: ', 'sha256:  ', MphfFixture::preface(7, $hash)).$content,
        ];
        foreach ($variants as $name => $data) {
            file_put_contents($this->directory.'/variant', $data);
            $this->assertFalse($service->hasValidChecksum($this->directory.'/variant'), $name);
        }

        $this->assertTrue($service->hasValidChecksum($good));
    }

    public function testPublishAndCleanup(): void
    {
        $service = new MphfStorageService('memory', $this->directory);
        $service->ensureDirectory();
        $this->validFile($this->directory.'/new.tmp');
        $service->publish($this->directory.'/new.tmp', '20260102-0000.mphf');
        $this->assertSame(0o444, fileperms($this->directory.'/20260102-0000.mphf') & 0o777);
        touch($this->directory.'/20260101-0000.mphf');
        touch($this->directory.'/20251231-0000.mphf');
        touch($this->directory.'/stale.tmp');
        touch($this->directory.'/unrelated.txt');

        $service->cleanup('20260102-0000.mphf', '20260101-0000.mphf');

        $this->assertFileExists($this->directory.'/20260102-0000.mphf');
        $this->assertFileExists($this->directory.'/20260101-0000.mphf');
        $this->assertFileDoesNotExist($this->directory.'/20251231-0000.mphf');
        $this->assertFileDoesNotExist($this->directory.'/stale.tmp');
        $this->assertFileExists($this->directory.'/unrelated.txt');
        unlink($this->directory.'/unrelated.txt');
    }
}
