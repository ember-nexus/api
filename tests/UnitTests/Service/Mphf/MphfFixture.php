<?php

declare(strict_types=1);

namespace App\Tests\UnitTests\Service\Mphf;

/**
 * Creates `.mphf` file contents which follow the preface rules of lib/UuidToTypeMphfLookup/README.md, including the
 * padding of the preface to a multiple of 64 bytes.
 */
final class MphfFixture
{
    public static function preface(int $contentLength, string $sha256): string
    {
        $text = "MPHF\ngenerated by: test\ngenerated on: 2026-11-22 18:14\ncontent length: ".$contentLength."\nsha256: ".$sha256;
        $padding = (64 - (strlen($text) + 2) % 64) % 64;

        return $text.str_repeat(' ', $padding)."\n\n";
    }

    public static function file(string $content = 'payload'): string
    {
        return self::preface(strlen($content), hash('sha256', $content)).$content;
    }
}
